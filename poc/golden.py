#!/usr/bin/env python3
"""Helpers of the golden path suite (poc/poc-golden.sh, issue #23). No network, no cluster: files in, lines out.

    golden.py table --doc docs/POC-STATUS.md --env "lab host (Incus)" --results .state/golden.tsv
        write this run's column of the golden rule table in the doc, between the golden:begin and golden:end markers; the columns of
        other environments are kept, so the lab and a stranger's control plane fill the same table. Idempotent.
    golden.py audit <pods.json> "<node>=<trust> ..."
        print every pod outside the system namespaces that is private (no label, or private) and runs on a node that is not `own`
    golden.py cert <nebula-cert> <host.crt>
        print "<fingerprint> <issuer fingerprint> <lifetime in seconds>" of a Nebula certificate (expired or revoked ones too)
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import subprocess
import sys
from pathlib import Path

BEGIN = "<!-- golden:begin"
END = "<!-- golden:end -->"
FIXED = ["Rule", "Check", "What it proves"]
SYSTEM = {"kube-system", "kyverno", "cilium-spire", "kube-node-lease", "kube-public"}


def check_key(check_id: str) -> tuple:
    rule, _, n = check_id[1:].partition(".")
    return (int(rule), int(n or 0))


def parse_table(block: str) -> tuple[list[str], dict[str, dict]]:
    """The environment columns and the rows (check id -> {rule, desc, <env>: status}) of an existing table."""
    rows = [r for r in block.splitlines() if r.startswith("|")]
    if len(rows) < 2:
        return [], {}
    head = [c.strip() for c in rows[0].strip("|").split("|")]
    envs = head[len(FIXED):]
    out = {}
    for r in rows[2:]:
        cells = [c.strip() for c in r.strip("|").split("|")]
        if len(cells) != len(head):
            continue
        row = {"rule": cells[0], "desc": cells[2]}
        row.update(dict(zip(envs, cells[len(FIXED):])))
        out[cells[1]] = row
    return envs, out


def render(envs: list[str], rows: dict[str, dict], note: str) -> str:
    lines = [f"{BEGIN} {note} -->", "| " + " | ".join(FIXED + envs) + " |", "| " + " | ".join([":---"] * (len(FIXED) + len(envs))) + " |"]
    for cid in sorted(rows, key=check_key):
        r = rows[cid]
        lines.append("| " + " | ".join([r["rule"], cid, r["desc"]] + [r.get(e, "-") for e in envs]) + " |")
    lines.append(END)
    return "\n".join(lines)


def update(doc: str, env: str, results: list[tuple[str, str, str, str]]) -> str:
    """doc with the table's column `env` set from results (rule, id, status, description); the rest of the doc is untouched."""
    if "|" in env:
        raise ValueError("the environment label cannot contain '|'")
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END), doc, flags=re.S)
    if not m:
        raise ValueError(f"no {BEGIN} ... {END} block in the doc")
    envs, rows = parse_table(m.group(0))
    if env not in envs:
        envs.append(env)
    for rule, cid, status, desc in results:
        row = rows.setdefault(cid, {"rule": rule})
        row["rule"], row["desc"], row[env] = rule, desc.replace("|", "/"), status
    note = "generated by poc/poc-golden.sh (GOLDEN_ENV=<column>); change the checks, not this table"
    return doc[:m.start()] + render(envs, rows, note) + doc[m.end():]


def read_results(path: str) -> list[tuple[str, str, str, str]]:
    out = []
    for line in Path(path).read_text().splitlines():
        parts = line.split("\t")
        if len(parts) == 4:
            out.append(tuple(parts))
    return out


def audit(pods: dict, trust: dict[str, str]) -> list[str]:
    bad = []
    for p in pods.get("items", []):
        m, node = p["metadata"], p["spec"].get("nodeName", "")
        if m["namespace"] in SYSTEM or not node or p.get("status", {}).get("phase") in ("Succeeded", "Failed"):
            continue
        s = (m.get("labels") or {}).get("edge-mesh/sensitivity", "private")
        if s != "shareable" and trust.get(node) != "own":
            bad.append(f"{m['namespace']}/{m['name']} ({s}) on {node} ({trust.get(node) or 'no trust label'})")
    return bad


def cert_line(printed: str) -> str:
    c = json.loads(printed)[0]
    d = c["details"]
    t = lambda s: dt.datetime.fromisoformat(s.replace("Z", "+00:00"))  # noqa: E731
    issuer = d.get("issuer") or c["fingerprint"]  # a CA certificate is its own issuer
    return f"{c['fingerprint']} {issuer} {int((t(d['notAfter']) - t(d['notBefore'])).total_seconds())}"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("table")
    t.add_argument("--doc", required=True)
    t.add_argument("--env", required=True)
    t.add_argument("--results", required=True)
    a = sub.add_parser("audit")
    a.add_argument("pods")
    a.add_argument("trust")
    c = sub.add_parser("cert")
    c.add_argument("nebula_cert")
    c.add_argument("crt")
    args = ap.parse_args(argv)
    if args.cmd == "table":
        doc = Path(args.doc)
        doc.write_text(update(doc.read_text(), args.env, read_results(args.results)))
        print(f"table updated: column '{args.env}' in {args.doc}")
    elif args.cmd == "audit":
        trust = dict(x.split("=", 1) for x in args.trust.split())
        for line in audit(json.loads(Path(args.pods).read_text()), trust):
            print(line)
    else:
        printed = subprocess.run([args.nebula_cert, "print", "-json", "-path", args.crt], capture_output=True, text=True, check=True).stdout
        print(cert_line(printed))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
