#!/usr/bin/env python3
"""Learn mode (issue #77): what you see in the demo, the concept behind it, an analogy and where it is used for real.

    scripts/learn.py write     docs/LEARN.md and poc/page/whatsnew/learn.json, from the `learn` blocks of docs/FEATURES.yml
    scripts/learn.py check     both files are what the catalog generates now, and carry the hash of its learn data (exit 1 when stale)
    scripts/learn.py measure   how many features have a `learn` block, and how many the rule requires

The catalog is the only place the sentences are written. The generated files carry the SHA-256 of the data they were made from (the same idea
as the diagrams, scripts/diagrams.py; learn.json is compared byte for byte instead), so a stale copy fails `check`, tests/test_learn.py and CI. No network, no clock: same catalog, same bytes.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import features  # noqa: E402

ROOT = features.ROOT
DOC = ROOT / "docs" / "LEARN.md"
PAGE = ROOT / "poc" / "page" / "whatsnew" / "learn.json"


def rows(cat: dict) -> list[dict]:
    """The features that explain themselves: what the generated files are made from."""
    return [{"id": f["id"], "layer": f["layer"], "releases": f.get("releases") or [], **f["learn"],
             "proven_by": sorted({(p["suite"], ", ".join(map(str, p["steps"]))) for p in f["proven_by"]})}
            for f in cat["features"] if f.get("learn")]


def seal(data: list[dict]) -> str:
    return hashlib.sha256(json.dumps(data, sort_keys=True, ensure_ascii=True).encode()).hexdigest()


def markdown(cat: dict) -> str:
    data = rows(cat)
    out = ["---", "tipo: doc", "id: k8s-lan-party-learn", "version: 1.0.0", "fecha_alta: 2026-11-04", f"fecha_ultimo_cambio: {cat['meta']['fecha_ultimo_cambio']}",
           "categoria: plataforma", "dueno_agente: casa-orquestador", "pieza: k8s-lan-party", "meta: ../meta.yml",
           "depende_de: [docs/FEATURES.yml, scripts/learn.py]", "lo_usan: [README.md, docs/TRY-IT.md]", "docs: [docs/FEATURES.yml, docs/POC-STATUS.md]",
           "scripts: [scripts/learn.py]", "runbooks: []", "tags: [learn, concepts, platform-engineering, generated]", "---", "",
           "# Learn mode: what you saw, and where it is used for real", "",
           f"<!-- learn-source-sha256: {seal(data)} -->",
           "<!-- GENERATED by scripts/learn.py from the `learn` blocks of docs/FEATURES.yml (issue #77). Do not edit: change the catalog, then "
           "`make learn`. `make learn-check` and CI fail when this file is stale. -->", "",
           "k8s-lan-party looks like a game, but each thing you see in it is a platform engineering concept running end to end. This page "
           "says, for each feature, **what the concept is**, **an everyday analogy**, **where it is used for real**, **where you see it** "
           "and **which suite steps prove it**.", "",
           "The last column is not decoration: `make regression` runs those steps in a fixed order and writes the same table every time "
           "([POC-STATUS.md](POC-STATUS.md)), so a row here is a claim a test checks, not a story. "
           "The concepts are those of a Kubernetes platform engineer: admission, tenancy, placement, network policy, revocation.", ""]
    for lid, title in features.LAYERS.items():
        mine = [r for r in data if r["layer"] == lid]
        if not mine:
            continue
        out += [f"## {title}", "", "| Feature | Concept | Analogy | Used for real | Seen in | Proven by |", "| :--- | :--- | :--- | :--- | :--- | :--- |"]
        for r in mine:
            proof = "; ".join(f"`{s}` {steps}" for s, steps in r["proven_by"])
            out.append(f"| `{r['id']}` | {r['concept']} | {r['analogy']} | {r['real_world']} | {r['seen_in']} | {proof} |")
        out.append("")
    return "\n".join(out)


def page_json(cat: dict) -> str:
    """For the public page, which has no YAML: per release, the cards of the features it shows (poc/page/whatsnew/news.py renders them)."""
    data, rel = rows(cat), {}
    for r in data:
        for v in r["releases"]:
            rel.setdefault(v, []).append({k: r[k] for k in ("id", "concept", "analogy", "real_world", "seen_in")})
    # no hash inside: poc/test_whatsnew.py scans every committed file for 64-character hex strings (a leaked key looks like one), and
    # `check` already compares this file byte for byte with what the catalog generates, which is a stronger seal
    return json.dumps({"releases": rel}, sort_keys=True, indent=1, ensure_ascii=True) + "\n"


def stale(cat: dict) -> list[str]:
    return [f"{p.relative_to(ROOT)}: not what docs/FEATURES.yml generates; run `make learn`"
            for p, want in ((DOC, markdown(cat)), (PAGE, page_json(cat))) if not p.is_file() or p.read_text(encoding="utf-8") != want]


def measure(cat: dict) -> str:
    fs = cat["features"]
    have, need = [f["id"] for f in fs if f.get("learn")], [f["id"] for f in fs if features.needs_learn(f)]
    return (f"{len(fs)} features; {len(have)} with a learn block; {len(need)} required "
            f"({sum(bool(f.get('user_facing')) for f in fs)} user_facing, {sum(bool(f.get('releases')) for f in fs)} shown by a release page); "
            f"missing: {', '.join(i for i in need if i not in have) or 'none'}")


def main() -> int:
    cmd, cat = (sys.argv[1:2] or [""])[0], features.load()
    if cmd == "write":
        problems = features.validate(cat)
        if problems:
            print("\n".join(problems))
            return 1
        DOC.write_text(markdown(cat), encoding="utf-8")
        PAGE.write_text(page_json(cat), encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)} and {PAGE.relative_to(ROOT)}: {measure(cat)}")
        return 0
    if cmd == "check":
        problems = stale(cat)
        print("\n".join(problems) or "docs/LEARN.md and learn.json: generated from the current docs/FEATURES.yml")
        return 1 if problems else 0
    if cmd == "measure":
        print(measure(cat))
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
